# NOTE: requires python-docx, which is NOT in requirements.txt (pip install python-docx).
"""Build the Chapters 2-9 draft (Markdown and DOCX).

Two steps:
  1. --expand SRC : expand "<!-- include figures/x.md -->" markers in SRC (tables
     generated by make_report_artifacts.py) and write the Markdown deliverable.
  2. (always)     : convert the Markdown deliverable to DOCX.

The Markdown file in docs/report/ is the reviewable source. To rebuild only the
DOCX after editing it, run without --expand. If artifacts are regenerated, re-run
make_report_artifacts.py and paste the updated tables (or re-expand from a source
that still has include markers).

Requires python-docx (not in requirements.txt):  pip install python-docx

Usage (from the repository root):
  python docs/report/scripts/build_report.py [--expand SRC]
"""

from __future__ import annotations

import argparse
import re
from pathlib import Path

from docx import Document
from docx.enum.table import WD_TABLE_ALIGNMENT
from docx.enum.text import WD_ALIGN_PARAGRAPH, WD_BREAK, WD_COLOR_INDEX
from docx.oxml import OxmlElement
from docx.oxml.ns import qn
from docx.shared import Inches, Pt, RGBColor

REPORT_DIR = Path(__file__).resolve().parents[1]
MD_PATH = REPORT_DIR / "TraceAdvisor_295B_Final_Report_Ch2-9_DRAFT.md"
DOCX_PATH = REPORT_DIR / "TraceAdvisor_295B_Final_Report_Ch2-9_DRAFT.docx"
FONT = "Times New Roman"
INCLUDE_RE = re.compile(r"^<!--\s*include\s+(\S+)\s*-->\s*$")
TOKEN_RE = re.compile(r"(\[TBD[^\]]*\]|\*\*[^*]+\*\*|`[^`]+`|\*[^*\s][^*]*\*)")


def expand(src: Path) -> str:
    out = []
    for line in src.read_text().splitlines():
        m = INCLUDE_RE.match(line.strip())
        if m:
            out.append((REPORT_DIR / m.group(1)).read_text().rstrip("\n"))
        else:
            out.append(line)
    return "\n".join(out) + "\n"


def add_runs(par, text: str, size: float | None = None, italic: bool = False, bold: bool = False):
    for part in TOKEN_RE.split(text):
        if not part:
            continue
        run_bold, run_italic, mono, tbd = bold, italic, False, False
        content = part
        if part.startswith("[TBD"):
            tbd = True
            run_bold = True
        elif part.startswith("**") and part.endswith("**"):
            content, run_bold = part[2:-2], True
        elif part.startswith("`") and part.endswith("`"):
            content, mono = part[1:-1], True
        elif part.startswith("*") and part.endswith("*") and len(part) > 2:
            content, run_italic = part[1:-1], not italic
        if tbd:
            # A TBD may itself contain inline code; keep it as plain highlighted text.
            content = content.replace("`", "")
        run = par.add_run(content)
        run.bold = run_bold
        run.italic = run_italic
        run.font.name = "Courier New" if mono else FONT
        if size:
            run.font.size = Pt(size - (1 if mono else 0))
        elif mono:
            run.font.size = Pt(10)
        if tbd:
            run.font.highlight_color = WD_COLOR_INDEX.YELLOW
            run.font.color.rgb = RGBColor(0x9C, 0x00, 0x06)


def set_cell_shading(cell, hex_fill: str):
    tc_pr = cell._tc.get_or_add_tcPr()
    shd = OxmlElement("w:shd")
    shd.set(qn("w:val"), "clear")
    shd.set(qn("w:color"), "auto")
    shd.set(qn("w:fill"), hex_fill)
    tc_pr.append(shd)


def add_table(doc, rows: list[list[str]]):
    header, body = rows[0], rows[1:]
    ncols = len(header)
    size = 7.5 if ncols >= 9 else (8.5 if ncols >= 6 else 10)
    table = doc.add_table(rows=1 + len(body), cols=ncols)
    table.style = "Table Grid"
    table.alignment = WD_TABLE_ALIGNMENT.CENTER
    for r, row in enumerate([header] + body):
        for c in range(ncols):
            cell = table.cell(r, c)
            cell.text = ""
            par = cell.paragraphs[0]
            par.paragraph_format.space_after = Pt(0)
            add_runs(par, row[c] if c < len(row) else "", size=size, bold=(r == 0))
            if r == 0:
                set_cell_shading(cell, "D9D9D9")
    doc.add_paragraph().paragraph_format.space_after = Pt(2)


def add_toc_field(doc):
    par = doc.add_paragraph()
    run = par.add_run()
    for tag, attr in (("w:fldChar", "begin"), ("w:instrText", None), ("w:fldChar", "separate")):
        el = OxmlElement(tag)
        if attr:
            el.set(qn("w:fldCharType"), attr)
        else:
            el.set(qn("xml:space"), "preserve")
            el.text = 'TOC \\o "1-3" \\h \\z \\u'
        run._r.append(el)
    run2 = par.add_run("Right-click and choose Update Field to build the table of contents.")
    run2.italic = True
    end = OxmlElement("w:fldChar")
    end.set(qn("w:fldCharType"), "end")
    run2._r.append(end)


def configure(doc):
    sec = doc.sections[0]
    sec.page_width, sec.page_height = Inches(8.5), Inches(11)
    sec.top_margin, sec.bottom_margin = Inches(1.3), Inches(1.0)
    sec.left_margin, sec.right_margin = Inches(1.5), Inches(1.0)
    normal = doc.styles["Normal"]
    normal.font.name = FONT
    normal.font.size = Pt(12)
    normal.element.rPr.rFonts.set(qn("w:eastAsia"), FONT)
    normal.paragraph_format.space_after = Pt(6)
    normal.paragraph_format.line_spacing = 1.15
    for name, size in (("Heading 1", 16), ("Heading 2", 14), ("Heading 3", 12), ("Title", 20)):
        st = doc.styles[name]
        st.font.name = FONT
        st.font.size = Pt(size)
        st.font.color.rgb = RGBColor(0, 0, 0)
        rpr = st.element.get_or_add_rPr()
        fonts = rpr.find(qn("w:rFonts"))
        if fonts is None:
            fonts = OxmlElement("w:rFonts")
            rpr.append(fonts)
        for a in ("w:ascii", "w:hAnsi", "w:eastAsia", "w:cs"):
            fonts.set(qn(a), FONT)
    cap = doc.styles["Caption"]
    cap.font.name = FONT
    cap.font.size = Pt(10)
    cap.font.color.rgb = RGBColor(0, 0, 0)
    footer = sec.footer.paragraphs[0]
    footer.alignment = WD_ALIGN_PARAGRAPH.CENTER
    r = footer.add_run()
    for tag, attr in (("w:fldChar", "begin"), ("w:instrText", None), ("w:fldChar", "end")):
        el = OxmlElement(tag)
        if attr:
            el.set(qn("w:fldCharType"), attr)
        else:
            el.set(qn("xml:space"), "preserve")
            el.text = "PAGE"
        r._r.append(el)


def to_docx(md: str):
    doc = Document()
    configure(doc)
    lines = md.splitlines()
    i, first_h1_seen, toc_added = 0, False, False
    while i < len(lines):
        line = lines[i]
        s = line.strip()
        if not s:
            i += 1
            continue
        if s.startswith("|"):
            rows = []
            while i < len(lines) and lines[i].strip().startswith("|"):
                cells = [c.strip() for c in lines[i].strip().strip("|").split("|")]
                if not all(re.fullmatch(r":?-{3,}:?", c) for c in cells):
                    rows.append(cells)
                i += 1
            add_table(doc, rows)
            continue
        m = re.match(r"^(#{1,3})\s+(.*)$", s)
        if m:
            level, text = len(m.group(1)), m.group(2)
            if level == 1 and not first_h1_seen:
                doc.add_paragraph(text, style="Title")
                first_h1_seen = True
            else:
                if level == 1 and not toc_added:
                    doc.add_paragraph("Table of Contents (Chapters 2–9 draft)", style="Heading 1")
                    add_toc_field(doc)
                    toc_added = True
                if level == 1:
                    doc.add_paragraph().add_run().add_break(WD_BREAK.PAGE)
                doc.add_paragraph(text, style=f"Heading {level}")
            i += 1
            continue
        img = re.match(r"^!\[[^\]]*\]\(([^)]+)\)$", s)
        if img:
            par = doc.add_paragraph()
            par.alignment = WD_ALIGN_PARAGRAPH.CENTER
            par.add_run().add_picture(str(REPORT_DIR / img.group(1)), width=Inches(5.0))
            i += 1
            continue
        if re.match(r"^\*(Figure|Table) \d+\.\d+\.", s) and s.endswith("*"):
            par = doc.add_paragraph(style="Caption")
            add_runs(par, s[1:-1], size=10, italic=True)
            if s.startswith("*Figure"):
                par.alignment = WD_ALIGN_PARAGRAPH.CENTER
            i += 1
            continue
        if s.startswith(">"):
            par = doc.add_paragraph()
            par.paragraph_format.left_indent = Inches(0.3)
            add_runs(par, s.lstrip("> ").strip(), size=10.5)
            i += 1
            continue
        b = re.match(r"^- (.*)$", s)
        if b:
            add_runs(doc.add_paragraph(style="List Bullet"), b.group(1))
            i += 1
            continue
        n = re.match(r"^\d+\. (.*)$", s)
        if n:
            add_runs(doc.add_paragraph(style="List Number"), n.group(1))
            i += 1
            continue
        add_runs(doc.add_paragraph(), s)
        i += 1
    doc.core_properties.title = "TraceAdvisor CMPE 295B Final Report, Chapters 2-9 (Draft)"
    doc.core_properties.author = "Shivani Jariwala, Meghana Koti, Sonali Lonkar, Sofia Silva"
    import datetime as _dt
    _now = _dt.datetime.now()
    doc.core_properties.created = _now
    doc.core_properties.modified = _now
    doc.core_properties.last_modified_by = "Shivani Jariwala"
    doc.core_properties.comments = ""
    doc.core_properties.subject = ""
    doc.save(DOCX_PATH)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--expand", type=Path, help="source with include markers")
    args = ap.parse_args()
    if args.expand:
        MD_PATH.write_text(expand(args.expand))
    to_docx(MD_PATH.read_text())
    print(f"Wrote {DOCX_PATH}")


if __name__ == "__main__":
    main()
